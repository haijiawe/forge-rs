//! HTTP/1.1 and WebSocket surface for the forge session log.
//!
//! Layer L3. This module is the Rust half of `forge-go/internal/server`. The
//! event log is the only state that survives a restart: every list, detail and
//! stream answer is re-derived from the log on use, and every mutation appends
//! through [`Server::append`] so there is exactly one seq counter per session.
//!
//! There is deliberately no async runtime. One thread per connection is enough
//! for one process per project, and it keeps the write path easy to reason
//! about: a request either holds the single append lock or it waits.

