// ---------------------------------------------------------------------------
// Small encoders. The workspace budget has no base64/SHA crates, and these two
// primitives are the only ones the wire needs: token/session ids and the RFC
// 6455 handshake. They are local so no dependency has to be negotiated.
// ---------------------------------------------------------------------------

/// Standard base64 **with** padding, which RFC 6455 §4.2.2 requires for
/// `Sec-WebSocket-Accept`. `base64_encode` never pads because every other caller
/// here wants the unpadded base64url form (the token, the cursor); using it for
/// the accept produced a value one `=` short for two out of three keys, which
/// browsers reject — and the RFC's own sample key happens to need no padding, so
/// the existing tests never noticed.
fn base64_encode_padded(data: &[u8]) -> String {
    let mut out = base64_encode(data, false);
    for _ in 0..(4 - out.len() % 4) % 4 {
        out.push('=');
    }
    out
}

/// Strict standard base64, for an attachment body a client sent.
///
/// `None` for anything that is not exactly base64: a wrong character, a bad
/// length, padding in the middle, or whitespace. Being lenient here would mean
/// storing bytes that are not the ones the client thought it sent.
fn base64_decode(text: &str) -> Option<Vec<u8>> {
    let bytes = text.as_bytes();
    if !bytes.len().is_multiple_of(4) {
        return None;
    }
    let mut out = Vec::with_capacity(bytes.len() / 4 * 3);
    let last_chunk = bytes.len() / 4;
    for (chunk_index, chunk) in bytes.chunks(4).enumerate() {
        let padding = chunk.iter().filter(|byte| **byte == b'=').count();
        if padding > 2 {
            return None;
        }
        if padding > 0 && chunk_index + 1 != last_chunk {
            return None; // padding is only ever at the end
        }
        let mut word = 0u32;
        for (index, byte) in chunk.iter().enumerate() {
            let value = match byte {
                b'A'..=b'Z' => byte - b'A',
                b'a'..=b'z' => byte - b'a' + 26,
                b'0'..=b'9' => byte - b'0' + 52,
                b'+' => 62,
                b'/' => 63,
                b'=' if index >= 4 - padding => 0,
                _ => return None,
            };
            word = (word << 6) | u32::from(value);
        }
        out.push((word >> 16) as u8);
        if padding < 2 {
            out.push((word >> 8) as u8);
        }
        if padding < 1 {
            out.push(word as u8);
        }
    }
    Some(out)
}

fn base64_encode(data: &[u8], url_safe: bool) -> String {
    let alphabet: &[u8; 64] = if url_safe {
        b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_"
    } else {
        b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
    };
    let mut out = String::with_capacity(data.len().div_ceil(3) * 4);
    for chunk in data.chunks(3) {
        let b0 = chunk[0] as u32;
        let b1 = chunk.get(1).copied().unwrap_or(0) as u32;
        let b2 = chunk.get(2).copied().unwrap_or(0) as u32;
        let word = (b0 << 16) | (b1 << 8) | b2;
        out.push(alphabet[((word >> 18) & 63) as usize] as char);
        out.push(alphabet[((word >> 12) & 63) as usize] as char);
        if chunk.len() > 1 {
            out.push(alphabet[((word >> 6) & 63) as usize] as char);
        }
        if chunk.len() > 2 {
            out.push(alphabet[(word & 63) as usize] as char);
        }
    }
    out
}

fn base64_url_decode(text: &str) -> Option<Vec<u8>> {
    fn digit(byte: u8) -> Option<u8> {
        match byte {
            b'A'..=b'Z' => Some(byte - b'A'),
            b'a'..=b'z' => Some(byte - b'a' + 26),
            b'0'..=b'9' => Some(byte - b'0' + 52),
            b'-' => Some(62),
            b'_' => Some(63),
            _ => None,
        }
    }
    let bytes = text.as_bytes();
    if bytes.len() % 4 == 1 {
        return None;
    }
    let mut out = Vec::with_capacity(bytes.len() * 3 / 4);
    let mut i = 0;
    while i < bytes.len() {
        let take = (bytes.len() - i).min(4);
        let mut word: u32 = 0;
        let mut filled = 0;
        for j in 0..take {
            if bytes[i + j] == b'=' {
                break;
            }
            word = (word << 6) | digit(bytes[i + j])? as u32;
            filled += 1;
        }
        out.push((word >> 16) as u8);
        if filled > 2 {
            out.push((word >> 8) as u8);
        }
        if filled > 3 {
            out.push(word as u8);
        }
        i += 4;
    }
    Some(out)
}

fn hex_to_bytes(text: &str) -> Option<Vec<u8>> {
    if !text.len().is_multiple_of(2) {
        return None;
    }
    fn nibble(byte: u8) -> Option<u8> {
        match byte {
            b'0'..=b'9' => Some(byte - b'0'),
            b'a'..=b'f' => Some(byte - b'a' + 10),
            b'A'..=b'F' => Some(byte - b'A' + 10),
            _ => None,
        }
    }
    let bytes = text.as_bytes();
    let mut out = Vec::with_capacity(bytes.len() / 2);
    for pair in bytes.chunks(2) {
        out.push((nibble(pair[0])? << 4) | nibble(pair[1])?);
    }
    Some(out)
}

fn random_bytes(count: usize) -> Result<Vec<u8>> {
    // `new_id` is the workspace CSPRNG boundary; each call yields 16 bytes.
    let mut out = Vec::with_capacity(count);
    while out.len() < count {
        let id = forge_core::new_id()?;
        let mut bytes = hex_to_bytes(&id).ok_or_else(|| {
            Error::new(
                ErrorKind::Invalid,
                "server: id source returned non-hex bytes",
            )
        })?;
        out.append(&mut bytes);
    }
    out.truncate(count);
    Ok(out)
}

fn crockford_base32(bytes: &[u8]) -> String {
    let mut out = String::with_capacity((bytes.len() * 8).div_ceil(5));
    let mut accumulator: u32 = 0;
    let mut bits = 0;
    for byte in bytes {
        accumulator = (accumulator << 8) | *byte as u32;
        bits += 8;
        while bits >= 5 {
            bits -= 5;
            let index = ((accumulator >> bits) & 31) as usize;
            out.push(B32_ALPHABET[index] as char);
        }
    }
    if bits > 0 {
        out.push(B32_ALPHABET[((accumulator << (5 - bits)) & 31) as usize] as char);
    }
    out
}

fn new_session_id() -> Result<String> {
    let bytes = random_bytes(16)?;
    Ok(format!("s_{}", crockford_base32(&bytes)))
}

