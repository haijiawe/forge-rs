//! Copies the browser bundle into OUT_DIR so the server can embed it with no
//! runtime dependency on the checkout layout. `Cargo.toml` is frozen, so this
//! file is picked up by Cargo's automatic build-script discovery: it needs no
//! `build-dependencies` declaration and uses only std.
//!
//! When `make web` has not run, the generated asset table still contains a
//! 200-status placeholder page. The server must answer on every checkout; a
//! missing `web/dist` is a build state, not a reason to fail HTTP requests.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};

const PLACEHOLDER: &str = r#"<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>Forge</title></head>
<body><h1>Forge</h1><p>The browser bundle is not built in this checkout.</p>
<p>Run <code>make web</code> from the workspace root, then rebuild the server.</p></body></html>
"#;

fn main() {
    let manifest =
        PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR set by cargo"));
    let dist = manifest.join("..").join("..").join("web").join("dist");
    println!("cargo:rerun-if-changed={}", dist.display());

    let out = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR set by cargo"));
    let target = out.join("embedded_assets.rs");

    let mut assets: Vec<(String, Vec<u8>)> = Vec::new();
    if dist.join("index.html").is_file() {
        collect(&dist, &dist, &mut assets);
    }
    if assets.is_empty() {
        assets.push(("index.html".to_string(), PLACEHOLDER.as_bytes().to_vec()));
    }
    // index.html must be the shell even if the walk found it in an odd order.
    assets.sort_by(|a, b| a.0.cmp(&b.0));

    let mut rust = String::from(
        "// Generated by crates/server/build.rs. A missing web/dist becomes a placeholder.\n\
         pub static EMBEDDED_ASSETS: &[(&str, &[u8])] = &[\n",
    );
    for (name, bytes) in &assets {
        rust.push_str("    (");
        rust.push_str(&rust_string(name));
        rust.push_str(", b\"");
        for byte in bytes {
            match *byte {
                b'\\' => rust.push_str("\\\\"),
                b'"' => rust.push_str("\\\""),
                b'\n' => rust.push_str("\\n"),
                b'\r' => rust.push_str("\\r"),
                b'\t' => rust.push_str("\\t"),
                0x20..=0x7e => rust.push(*byte as char),
                other => rust.push_str(&format!("\\x{:02x}", other)),
            }
        }
        rust.push_str("\"),\n");
    }
    rust.push_str("];\n");
    fs::write(&target, rust).expect("write generated asset table");
}

fn collect(root: &Path, dir: &Path, out: &mut Vec<(String, Vec<u8>)>) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect(root, &path, out);
            continue;
        }
        if !path.is_file() {
            continue;
        }
        let Ok(bytes) = fs::read(&path) else {
            continue;
        };
        // Forward slashes are the wire spelling, on every host.
        let name = path
            .strip_prefix(root)
            .unwrap_or(&path)
            .to_string_lossy()
            .replace('\\', "/");
        out.push((name, bytes));
    }
}

fn rust_string(value: &str) -> String {
    let mut out = String::from("\"");
    for ch in value.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if c.is_ascii_graphic() || c == ' ' => out.push(c),
            c => out.push_str(&format!("\\u{{{:x}}}", c as u32)),
        }
    }
    out.push('"');
    out
}
